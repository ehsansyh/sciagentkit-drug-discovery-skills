"""Tests for the cross-tool agent setup (sciagent init-agent / sync-skills).

These use only the standard library plus sciagentkit.agent_config, so they run
without rdkit, typer, or the MCP stack installed.
"""
from __future__ import annotations

import json
import tomllib
from pathlib import Path

from sciagentkit import agent_config as ac


def _make_repo(tmp_path):
    (tmp_path / "src" / "sciagentkit").mkdir(parents=True)
    (tmp_path / "scripts").mkdir()
    (tmp_path / "scripts" / "start_mcp.py").write_text("# launcher", encoding="utf-8")
    skills = tmp_path / ".claude" / "skills"
    for name in ("smiles-analysis", "report"):
        d = skills / name
        d.mkdir(parents=True)
        (d / "SKILL.md").write_text(f"---\nname: {name}\n---\n", encoding="utf-8")
    return tmp_path


def test_repo_root_detected_from_subdir(tmp_path):
    root = _make_repo(tmp_path)
    assert ac.repo_root(root / "src" / "sciagentkit") == root


def test_mcp_config_is_cross_platform(tmp_path):
    root = _make_repo(tmp_path)
    cfg = ac.mcp_server_config(root)
    assert cfg["command"] == "python"
    assert cfg["args"][0].endswith("start_mcp.py")
    assert "bash" not in json.dumps(cfg)


def test_sync_skills_mirrors_canonical(tmp_path):
    root = _make_repo(tmp_path)
    target = root / "plugins" / "x" / "skills"
    written = ac.sync_skills(root, [target])
    assert len(written) == 2
    assert (target / "smiles-analysis" / "SKILL.md").exists()
    assert (target / "report" / "SKILL.md").exists()


def test_init_gemini_writes_config_and_skills(tmp_path):
    root = _make_repo(tmp_path)
    ac.init_agents(root, ["gemini"])
    assert (root / "GEMINI.md").exists()
    settings = json.loads((root / ".gemini" / "settings.json").read_text(encoding="utf-8"))
    assert "sciagentkit" in settings["mcpServers"]
    assert (root / ".gemini" / "skills" / "smiles-analysis" / "SKILL.md").exists()


def test_init_gemini_merges_existing_settings(tmp_path):
    root = _make_repo(tmp_path)
    settings_path = root / ".gemini" / "settings.json"
    settings_path.parent.mkdir(parents=True)
    settings_path.write_text(json.dumps({"mcpServers": {"other": {"command": "x"}}, "theme": "dark"}), encoding="utf-8")
    ac.init_agents(root, ["gemini"])
    settings = json.loads(settings_path.read_text(encoding="utf-8"))
    assert settings["theme"] == "dark"
    assert "other" in settings["mcpServers"]
    assert "sciagentkit" in settings["mcpServers"]


def test_init_all_covers_every_tool(tmp_path):
    root = _make_repo(tmp_path)
    result = ac.init_agents(root, ["all"])
    assert set(result) == set(ac.SUPPORTED_TOOLS)
    assert (root / "CLAUDE.md").exists()
    assert (root / "AGENTS.md").exists()
    assert (root / ".agents" / "skills" / "smiles-analysis" / "SKILL.md").exists()
    assert (root / ".codex" / "skills" / "smiles-analysis" / "SKILL.md").exists()
    assert (root / ".codex" / "config.toml").exists()
    assert (root / ".cursor" / "rules" / "sciagentkit.mdc").exists()


def test_init_codex_writes_parseable_portable_toml_and_skills(tmp_path):
    root = _make_repo(tmp_path)
    ac.init_agents(root, ["codex"])

    fragment = (root / "codex_config.fragment.toml").read_text(encoding="utf-8")
    parsed = tomllib.loads(fragment)
    cfg = parsed["mcp_servers"]["sciagentkit"]

    assert cfg["command"] == "python"
    assert cfg["args"] == ["scripts/start_mcp.py"]
    assert cfg["cwd"] == "."
    assert "\\" not in fragment
    assert str(root) not in fragment
    assert (root / ".codex" / "skills" / "report" / "SKILL.md").exists()


def test_init_agents_writes_portable_project_configs(tmp_path):
    root = _make_repo(tmp_path)
    ac.init_agents(root, ["all"])

    project_files = [
        root / ".mcp.json",
        root / ".mcp" / "sciagentkit.json",
        root / ".gemini" / "settings.json",
        root / "codex_config.fragment.toml",
        root / ".codex" / "config.toml",
    ]
    for path in project_files:
        text = path.read_text(encoding="utf-8")
        assert str(root) not in text
        assert "C:\\Users" not in text


def test_committed_agent_configs_do_not_embed_machine_paths():
    root = Path(__file__).resolve().parents[1]
    checked = [
        root / ".mcp.json",
        root / ".mcp" / "sciagentkit.example.json",
        root / ".mcp" / "sciagentkit.json",
        root / ".gemini" / "settings.json",
        root / "codex_config.fragment.toml",
        root / ".codex" / "config.toml",
    ]
    for path in checked:
        if not path.exists():
            # These files are generated by `sciagent init-agent`; a fresh checkout
            # may not contain them. Only committed configs are checked for leaked paths.
            continue
        text = path.read_text(encoding="utf-8")
        assert "C:\\Users" not in text
        assert "/Users/" not in text
        assert "/home/" not in text


def test_portable_skill_frontmatter_uses_only_name_and_description():
    root = Path(__file__).resolve().parents[1]
    skill_roots = [
        root / ".claude" / "skills",
        root / ".gemini" / "skills",
        root / ".codex" / "skills",
        root / "plugins" / "claude-code-sciagentkit" / "skills",
        root / "skills" / "openclaw",
    ]

    for skill_root in skill_roots:
        for skill_md in sorted(skill_root.glob("*/SKILL.md")):
            lines = skill_md.read_text(encoding="utf-8-sig").splitlines()
            assert lines[0] == "---", skill_md
            end = lines.index("---", 1)
            keys = {line.split(":", 1)[0] for line in lines[1:end] if ":" in line}
            assert keys == {"name", "description"}, f"{skill_md}: {sorted(keys)}"


