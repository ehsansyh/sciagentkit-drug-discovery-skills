def test_skill_descriptions_are_discovery_oriented():
    root = Path(__file__).resolve().parents[1]
    skill_paths = []
    for base in [
        root / ".claude" / "skills",
        root / ".agents" / "skills",
        root / ".agents" / "skills",
        root / ".codex" / "skills",
        root / ".gemini" / "skills",
        root / "plugins" / "claude-code-sciagentkit" / "skills",
        root / "skills" / "openclaw",
    ]:
        if base.exists():
            skill_paths.extend(sorted(base.glob("*/SKILL.md")))

    assert skill_paths
    for skill_path in skill_paths:
        text = skill_path.read_text(encoding="utf-8")
        assert text.startswith("---\n"), skill_path
        frontmatter = text.split("---", 2)[1]
        metadata = {}
        for line in frontmatter.strip().splitlines():
            key, value = line.split(":", 1)
            metadata[key.strip()] = value.strip().strip('"')
        assert set(metadata) == {"name", "description"}, skill_path
        assert metadata["description"].startswith("Use when"), skill_path
        assert len(metadata["description"]) <= 500, skill_path


def test_unknown_tool_raises(tmp_path):
    root = _make_repo(tmp_path)
    try:
        ac.init_agents(root, ["bogus"])
    except ValueError as exc:
        assert "bogus" in str(exc)
    else:
        raise AssertionError("expected ValueError for unknown tool")
